import time
from typing import Dict


# Набір номіналів монет
COINS = [50, 25, 10, 5, 2, 1]


def find_coins_greedy(amount: int) -> Dict[int, int]:
    """
    Жадібний алгоритм для видачі решти.
    Вибирає найбільші доступні номінали монет спочатку.

    Args:
        amount: Сума решти для видачі

    Returns:
        Словник з кількістю монет кожного номіналу

    Складність: O(n), де n - кількість номіналів монет
    """
    if amount <= 0:
        return {}

    result = {}
    remaining = amount

    for coin in COINS:
        if remaining >= coin:
            count = remaining // coin
            result[coin] = count
            remaining -= coin * count

    return result


def find_min_coins(amount: int) -> Dict[int, int]:
    """
    Алгоритм динамічного програмування для знаходження мінімальної кількості монет.
    Знаходить оптимальний спосіб видачі решти з мінімальною кількістю монет.

    Args:
        amount: Сума решти для видачі

    Returns:
        Словник з номіналами монет та їх кількістю

    Складність: O(amount * n), де n - кількість номіналів монет
    """
    if amount <= 0:
        return {}

    # Ініціалізація таблиці для динамічного програмування
    # dp[i] зберігає мінімальну кількість монет для суми i
    dp = [float("inf")] * (amount + 1)
    dp[0] = 0

    # parent[i] зберігає номінал монети, яку використали для досягнення суми i
    parent = [-1] * (amount + 1)

    # Заповнення таблиці
    for i in range(1, amount + 1):
        for coin in COINS:
            if coin <= i and dp[i - coin] + 1 < dp[i]:
                dp[i] = dp[i - coin] + 1
                parent[i] = coin

    # Якщо неможливо скласти суму
    if dp[amount] == float("inf"):
        return {}

    # Відновлення рішення з таблиці
    result = {}
    current = amount
    while current > 0:
        coin = parent[current]
        result[coin] = result.get(coin, 0) + 1
        current -= coin

    return result


def compare_algorithms(test_amounts: list) -> None:
    """
    Порівняння ефективності жадібного алгоритму та динамічного програмування.

    Args:
        test_amounts: Список сум для тестування
    """
    print("=" * 80)
    print("ПОРІВНЯННЯ АЛГОРИТМІВ ВИДАЧІ РЕШТИ")
    print("=" * 80)
    print(f"Номінали монет: {COINS}\n")

    for amount in test_amounts:
        print(f"\n{'─' * 80}")
        print(f"Сума: {amount} грн")
        print("─" * 80)

        # Тестування жадібного алгоритму
        start_time = time.perf_counter()
        greedy_result = find_coins_greedy(amount)
        greedy_time = time.perf_counter() - start_time
        greedy_coins = sum(greedy_result.values())

        print("\n🔹 Жадібний алгоритм:")
        print(f"   Результат: {dict(sorted(greedy_result.items(), reverse=True))}")
        print(f"   Кількість монет: {greedy_coins}")
        print(f"   Час виконання: {greedy_time:.8f} сек")

        # Тестування динамічного програмування
        start_time = time.perf_counter()
        dp_result = find_min_coins(amount)
        dp_time = time.perf_counter() - start_time
        dp_coins = sum(dp_result.values())

        print("\n🔹 Динамічне програмування:")
        print(f"   Результат: {dict(sorted(dp_result.items(), reverse=True))}")
        print(f"   Кількість монет: {dp_coins}")
        print(f"   Час виконання: {dp_time:.8f} сек")

        # Порівняння
        print("\n📊 Порівняння:")
        if greedy_coins == dp_coins:
            print(
                f"   ✅ Обидва алгоритми дали однакову кількість монет: {greedy_coins}"
            )
        else:
            print(f"   ⚠️  DP дав менше монет: {dp_coins} vs {greedy_coins} (жадібний)")

        if greedy_time < dp_time:
            speedup = dp_time / greedy_time
            print(f"   ⚡ Жадібний алгоритм швидший у {speedup:.2f} разів")
        else:
            speedup = greedy_time / dp_time
            print(f"   ⚡ DP швидший у {speedup:.2f} разів")


